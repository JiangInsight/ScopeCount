from pathlib import Path
from argparse import ArgumentParser
import pandas as pd

def main():
    root=Path(__file__).resolve().parents[1]
    ap=ArgumentParser()
    ap.add_argument("file",nargs="?",type=Path,default=root.parent/"runs"/"topology.tsv")
    ap.add_argument("--out",type=Path,default=root/"topology_numbers.tex")
    args=ap.parse_args()
    t=pd.read_csv(args.file,sep="\t",dtype={'digest':str})
    k=["dataset","bundle"]
    assert t.dataset.nunique()==8 and not t.duplicated(k+["rep","planner","tree"]).any()
    assert t.groupby(k).size().eq(12).all() and t.groupby(k).digest.nunique().eq(1).all()
    t["name"]=t.tree.where(t.planner.eq("min_reads"),"weighted")
    t["total"]=t.compile_ns+t.exec_ns
    t=t.groupby(k+["name"])[["ranks","updates","physical","total","exec_ns","oracle_widths"]].median().reset_index()
    wide={v:t.pivot(index=k,columns="name",values=v) for v in ["ranks","updates","physical","total","exec_ns","oracle_widths"]}
    r=wide["ranks"];c=wide["physical"];e=wide["exec_ns"];net=wide["total"]
    assert (c.weighted<=c.distinct).all() and (r.weighted>=r.distinct).all()
    total_r=r.groupby(level=0).sum()


    winners={v:int((total_r[v]<total_r[[q for q in ["distinct","frequency","field"] if q!=v]].min(axis=1)).sum()) for v in ["distinct","frequency","field"]}
    values=dict(TopoBundles=len(r),TopoDistinct=winners["distinct"],TopoFrequency=winners["frequency"],TopoField=winners["field"],
                TopoTies=8-sum(winners.values()),TopoStrict=int((c.weighted<c.distinct).sum()),
                TopoCost=f"{100*(1-c.weighted.sum()/c.distinct.sum()):.2f}",
                TopoWeightedSpeed=f"{e.distinct.sum()/e.weighted.sum():.2f}",
                TopoCompileFactor=f"{net.weighted.sum()/net.distinct.sum():.1f}",
                TopoRegression=int(wide["oracle_widths"].weighted.sum()),
                TopoFrequencyPct=f"{100*(total_r.frequency.sum()/total_r.distinct.sum()-1):.1f}",
                TopoFieldPct=f"{100*(total_r.field.sum()/total_r.distinct.sum()-1):.1f}",
                TopoRmin=int(total_r.frequency.min()))
    args.out.write_text("% Generated by artifact/topology_tables.py from topology.tsv\n"+
                        "".join(r"\newcommand{\%s}{%s}"%(k,v)+"\n" for k,v in values.items()),encoding="utf-8")
    print(total_r.to_string())
    print(values)
    print("per-source topology win/loss",wide["total"].groupby(level=0).sum().to_string())
    print("physical prices/ranks",c.sum().to_string())

if __name__=="__main__":main()
