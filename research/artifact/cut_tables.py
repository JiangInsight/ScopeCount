
from argparse import ArgumentParser
from pathlib import Path
import pandas as pd


def number(x):
    return f"{int(x):,}"


def main():
    root = Path(__file__).resolve().parents[1]
    parser = ArgumentParser()
    parser.add_argument("tsv", nargs="?", type=Path, default=root.parent / "runs" / "cut.tsv")
    parser.add_argument("--out", type=Path, default=root / "cut_numbers.tex")
    args = parser.parse_args()
    t = pd.read_csv(args.tsv, sep="\t", dtype={"keep_mask": str})
    keys = ["dataset", "first", "width"]
    if t.duplicated(keys + ["horizon"]).any():
        raise ValueError("Duplicate cut measurement")
    g = t.groupby(keys, sort=False)
    for key, frame in g:
        masks = [int(x) for x in frame.sort_values("horizon").keep_mask]
        if len(masks) != 7 or any(y & ~x for x, y in zip(masks, masks[1:])):
            raise ValueError(f"Incomplete or non-nested cut series {key}")
    t["pure"] = t[["all_tree", "all_cache"]].min(axis=1)
    t["strict"] = t.objective < t.pure
    t["saving"] = (t.pure - t.objective) / t.pure
    if (t.objective > t.pure).any() or ((t.objective <= 0) | (t.pure <= 0)).any():
        raise ValueError("Invalid admission objective")
    narrow = t[t.width <= 16]
    if not narrow.exhaustive.eq(1).all():
        raise ValueError("Missing enumeration checks")
    wide = t[t.width == 64]
    count_dup = len(t[t.cache_groups < t.width].drop_duplicates(keys))
    values = dict(CutDatasets=number(t.dataset.nunique()), CutPlans=number(len(g)), CutInstances=number(len(t)),
                  CutExhaustive=number(len(narrow)), CutStrict=number(t.strict.sum()), CutWideStrict=number(wide.strict.sum()),
                  CutWideInstances=number(len(wide)), CutWideSaving=f"{100*wide.saving.median():.2f}",
                  CutDup=number(count_dup), CutChanging=number((g.keep_mask.nunique() > 1).sum()),
                  CutKeepEarly=number(t.loc[t.horizon.eq(1), "kept"].sum()),
                  CutKeepLate=number(t.loc[t.horizon.eq(4096), "kept"].sum()))

    source = "% Generated by artifact/cut_tables.py from cut.tsv\n"
    source += "".join(r"\newcommand{\%s}{%s}" % (k, v) + "\n" for k, v in values.items())
    args.out.write_text(source, encoding="utf-8")


if __name__ == "__main__":
    main()
